package cmd

import (
	"fmt"
	"strings"
	"time"

	"github.com/agentclash/agentclash/cli/internal/output"
	"github.com/spf13/cobra"
)

// longRequestTimeout is the HTTP timeout for a route that calls a model
// synchronously. The default client timeout is 30 seconds, but the server
// gives the ranking-insights model call 45 seconds. It is a variable so that
// tests can make it short.
var longRequestTimeout = 2 * time.Minute

func init() {
	runCmd.AddCommand(runInsightsCmd)

	runInsightsCmd.Flags().String("provider-account", "", "Provider account ID that pays for the model call")
	runInsightsCmd.Flags().String("model", "", "Model ID to call through the provider account, for example gpt-4.1-mini")
	runInsightsCmd.MarkFlagRequired("provider-account")
	runInsightsCmd.MarkFlagRequired("model")
}

var runInsightsCmd = &cobra.Command{
	Use:   "insights <runId>",
	Short: "Ask a model to explain the ranking of a completed comparison run",
	Long: `Ask a model to explain the ranking of a completed comparison run.

The server sends the ranking and the scorecard of the run to the model that
you select, and returns the recommended winner, the tradeoffs, a summary of
each agent and a next step. The run must be a completed comparison run with
two or more ranked agents.

Each call is a paid model call on the provider account. The server limits the
number of calls for each run; a rate-limited call exits 75 and gives
retry_after_seconds. The CLI does not retry a call automatically.

The text comes from a model. Compare it with the deterministic ranking from
'agentclash run ranking <runId>' before you act on it.`,
	Example: `  # Explain the ranking of a run with a model of your provider account
  agentclash run insights <runId> --provider-account <providerAccountId> --model gpt-4.1-mini

  # Print only the recommended winner
  agentclash run insights <runId> --provider-account <providerAccountId> --model gpt-4.1-mini --json --query '.recommended_winner.label'`,
	Args: cobra.ExactArgs(1),
	RunE: func(cmd *cobra.Command, args []string) error {
		rc := GetRunContext(cmd)
		runID := args[0]
		providerAccountID, _ := cmd.Flags().GetString("provider-account")
		model, _ := cmd.Flags().GetString("model")

		if err := requireUUID("run ID", runID); err != nil {
			return err
		}
		if err := requireUUID("--provider-account", providerAccountID); err != nil {
			return err
		}
		model = strings.TrimSpace(model)
		if model == "" {
			return &cliError{
				Code:    "invalid_argument",
				Message: "--model must not be empty",
				Details: map[string]any{"argument": "--model"},
			}
		}

		body := map[string]any{
			"provider_account_id": providerAccountID,
			"model":               model,
		}

		sp := output.NewSpinner("Generating ranking insights (this can take up to a minute)...", flagQuiet)
		resp, err := rc.Client.WithRequestTimeout(longRequestTimeout).Post(cmd.Context(), "/v1/runs/"+runID+"/ranking-insights", body)
		if err != nil {
			sp.StopWithError("Ranking insights request failed")
			return err
		}
		if apiErr := resp.ParseError(); apiErr != nil {
			sp.StopWithError("Ranking insights request failed")
			return apiErr
		}
		sp.Stop()

		var result map[string]any
		if err := resp.DecodeJSON(&result); err != nil {
			return fmt.Errorf("decoding ranking insights response: %w", err)
		}

		if rc.Output.IsStructured() {
			return rc.Output.PrintRaw(result)
		}

		renderRunInsights(rc, result)
		rc.Output.PrintWarning("A model wrote this text. Compare it with the deterministic ranking: agentclash run ranking " + runID)
		return nil
	},
}

func renderRunInsights(rc *RunContext, result map[string]any) {
	winner := mapObject(result, "recommended_winner")
	rc.Output.PrintDetail("Winner", insightAgentLabel(winner))
	rc.Output.PrintDetail("Why it won", mapString(result, "why_it_won"))
	for _, pick := range []struct{ key, label string }{
		{"best_for_reliability", "Reliability pick"},
		{"best_for_cost", "Cost pick"},
		{"best_for_latency", "Latency pick"},
	} {
		rec := mapObject(result, pick.key)
		if rec == nil {
			continue
		}
		value := insightAgentLabel(rec)
		if reason := mapString(rec, "reason"); reason != "" {
			value += " - " + reason
		}
		rc.Output.PrintDetail(pick.label, value)
	}
	rc.Output.PrintDetail("Next step", mapString(result, "recommended_next_step"))
	rc.Output.PrintDetail("Confidence", mapString(result, "confidence_notes"))

	generatedBy := mapString(result, "provider_key")
	if modelID := mapString(result, "provider_model_id"); modelID != "" {
		generatedBy += " " + modelID
	}
	if at := mapString(result, "generated_at"); at != "" {
		generatedBy += " at " + at
	}
	rc.Output.PrintDetail("Generated by", strings.TrimSpace(generatedBy))

	w := rc.Output.Writer()
	if tradeoffs := mapStringSlice(result, "tradeoffs"); len(tradeoffs) > 0 {
		fmt.Fprintln(w)
		fmt.Fprintln(w, output.Bold("Tradeoffs:"))
		for _, tradeoff := range tradeoffs {
			fmt.Fprintf(w, "  - %s\n", tradeoff)
		}
	}

	summaries := mapSlice(result, "model_summaries")
	if len(summaries) == 0 {
		return
	}
	fmt.Fprintln(w)
	cols := []output.Column{{Header: "Agent"}, {Header: "Strongest"}, {Header: "Weakest"}, {Header: "Summary"}}
	rows := make([][]string, 0, len(summaries))
	for _, raw := range summaries {
		summary, ok := raw.(map[string]any)
		if !ok {
			continue
		}
		rows = append(rows, []string{
			insightAgentLabel(summary),
			mapString(summary, "strongest_dimension"),
			mapString(summary, "weakest_dimension"),
			mapString(summary, "summary"),
		})
	}
	rc.Output.PrintTable(cols, rows)
}

// insightAgentLabel gives the label of a run agent in an insight, or the run
// agent ID when the label is empty.
func insightAgentLabel(agent map[string]any) string {
	if label := mapString(agent, "label"); label != "" {
		return label
	}
	return mapString(agent, "run_agent_id")
}
