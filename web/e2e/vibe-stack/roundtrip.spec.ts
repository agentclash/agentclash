async function ownedCommand(name: string, command: string, args: string[], env: NodeJS.ProcessEnv) {
  await recordOwned("process", name);
  const child = spawn(command, args, { env, stdio: ["ignore", "pipe", "pipe"] });
  let stdout = "", stderr = "";
  child.stdout.on("data", value => { stdout += value; });
  child.stderr.on("data", value => { stderr += value; });
  const completion = new Promise<number | null>((resolve, reject) => { child.once("error", reject); child.once("exit", resolve); });
  await recordOwned("process", name, { phase: "started", child_pid: child.pid });
  const timeout = setTimeout(() => child.kill("SIGKILL"), 120_000);
  try {
    const code = await completion;
    await recordOwned("process", name, { phase: "exited", child_pid: child.pid, exit_code: code });
    return { code, stdout, stderr };
  } finally { clearTimeout(timeout); if (child.exitCode === null && child.signalCode === null) { child.kill("SIGTERM"); await completion; } }
}

